"""Aircraft type lookup, symbol class and flight-rules estimate for the traffic layer.

Data (generated by scripts/build_aircraft_types.py):
  data/aircraft-types.json   TYPECODE -> ICAO class (e.g. L1P, H2T)
  data/type-names.json       TYPECODE -> readable name
  data/hex-types.json.gz     icao24 -> TYPECODE (OpenSky aircraft database, Stand 11/2024)
"""

import gzip
import json
import re
import threading
from pathlib import Path

DATA = Path(__file__).resolve().parent / "data"
_lock = threading.Lock()
_tables = {}

SHAPES = ("heli", "gyro", "glider", "ulm", "prop1", "prop2", "turboprop", "bizjet", "airliner", "heavy", "other")

AIRLINER_TYPE_RE = re.compile(
    r"^(A2\d\d|A3\d\d|A1\d\dN?|A2\dN|A3\dN|A22|B7\d\d|B3\d[A-Z0-9]|B3[789]M|E1\d\d|E7\d[A-Z0-9]|E29|E19\d|"
    r"CRJ\d|CRJ[A-Z]|BCS\d|SU95|MD[89]\d|MD1\d|F100|F70|RJ\d\d|B1[01]\d|DC9|DC8|A400|AT7[26]|AT4\d|DH8[A-D]|SF34|E170|E75[LS])$")
GLIDER_TYPE_RE = re.compile(r"^(GLID|GLI\d|ASK\d|ASW\d|DG\d+|LS\d+|JS\d+|DUO|DISC|VENT|ARCU|NIMB|SZD\d+|PW\d|AS\d{2}[GK]|SF\d+|MOSQ|JANU)")
MOTORGLIDER_TYPE_RE = re.compile(r"^(DIMO|STRM|TMG|SF25|FALK|HK36|DV20|DA20)")
CALLSIGN_AIRLINE_RE = re.compile(r"^[A-Z]{3}\d{1,4}[A-Z]{0,2}$")
REGISTRATION_RE = re.compile(r"^[A-Z0-9]{1,2}-?[A-Z0-9]{3,5}$")

SHAPE_LABELS = {
    "heli": "Hubschrauber", "gyro": "Tragschrauber", "glider": "Segelflugzeug", "ulm": "Ultraleicht/Gleitschirm/Ballon",
    "prop1": "Kolbenmotor, einmotorig", "prop2": "Kolbenmotor, mehrmotorig", "turboprop": "Turboprop",
    "bizjet": "Business-/Kleinjet", "airliner": "Verkehrsflugzeug", "heavy": "Großraumflugzeug", "other": "Luftfahrzeug",
}


def _load():
    with _lock:
        if _tables:
            return _tables
        def read(name, default):
            try:
                return json.loads((DATA / name).read_text(encoding="utf-8"))
            except (OSError, ValueError):
                return default
        _tables["classes"] = read("aircraft-types.json", {})
        _tables["names"] = read("type-names.json", {})
        try:
            with gzip.open(DATA / "hex-types.json.gz", "rt", encoding="utf-8") as handle:
                _tables["hex"] = json.load(handle)
        except (OSError, ValueError):
            _tables["hex"] = {}
        return _tables


def lookup_hex_type(hex_code):
    return _load()["hex"].get(str(hex_code or "").lower(), "")


def type_name(type_code, feed_description=""):
    description = str(feed_description or "").strip()
    if description:
        return description[:64]
    return _load()["names"].get(str(type_code or "").upper(), "")


def type_class(type_code):
    return _load()["classes"].get(str(type_code or "").upper(), "")


def shape_for(type_code, emitter_category="", reported_category=""):
    """Symbol class: prefers the identified type, then ADS-B emitter category, then the feed category."""
    code = str(type_code or "").upper()
    cls = type_class(code)
    category = str(emitter_category or "").upper()
    if reported_category == "glider" or category == "B1" or GLIDER_TYPE_RE.match(code):
        return "glider"
    if reported_category in ("paraglider", "parachute") or category in ("B2", "B3", "B4"):
        return "ulm"
    if cls[:1] in ("H", "T") or category == "A7" or reported_category == "helicopter":
        return "heli"
    if cls[:1] == "G":
        return "gyro"
    if MOTORGLIDER_TYPE_RE.match(code) and category in ("", "A1"):
        return "prop1"
    engines = cls[1:2] if len(cls) == 3 and cls[1].isdigit() else ""
    engine_kind = cls[2:3] if len(cls) == 3 else ""
    if category in ("A5",) or (cls[:1] == "L" and engines in ("3", "4", "6", "8") and engine_kind in ("J", "T")):
        return "heavy" if category == "A5" or engine_kind == "J" or AIRLINER_TYPE_RE.match(code) else "turboprop"
    if engine_kind == "J":
        if category in ("A3", "A4") or AIRLINER_TYPE_RE.match(code):
            return "airliner"
        return "bizjet"
    if engine_kind == "T":
        return "airliner" if AIRLINER_TYPE_RE.match(code) else "turboprop"
    if engine_kind in ("P", "E"):
        return "prop1" if engines in ("", "1") else "prop2"
    # keine Klasse bekannt: nach ADS-B-Emitterkategorie
    if category == "A3" or category == "A4":
        return "airliner"
    if category == "A2":
        return "turboprop"
    if category == "A1":
        return "prop1"
    return "other"


def estimate_flight_rules(shape, callsign="", squawk="", altitude_ft=None, registration=""):
    """Rough estimate. ADS-B does not carry flight rules; this is only a display filter.

    ifr     Linien-/Geschäftsverkehr mit Airline-Rufzeichen, schwere Jets, oder oberhalb FL195
    ifr     auch Transpondercode 1000 (Mode-S-Konspikuitätscode, Europa)
    vfr     Transpondercode 7000, Segler/Ultraleicht/Tragschrauber, Kleinflugzeuge mit Kennzeichen als Rufzeichen
    unknown sonst (wird nur bei „Alle" gezeigt)
    """
    call = str(callsign or "").strip().upper()
    squawk = str(squawk or "").strip()
    if shape in ("airliner", "heavy"):
        return "ifr"
    if isinstance(altitude_ft, (int, float)) and altitude_ft >= 19500 and shape not in ("glider", "ulm"):
        return "ifr"
    if squawk == "7000" or shape in ("glider", "ulm", "gyro"):
        return "vfr"
    # 1000 = europäischer Mode-S-Konspikuitätscode (Kennung wird per Mode S mitgesendet): fast ausschließlich IFR-Verkehr.
    if squawk == "1000":
        return "ifr"
    airline_call = bool(CALLSIGN_AIRLINE_RE.match(call)) and not REGISTRATION_RE.match(call.replace("-", "")) or \
        (bool(CALLSIGN_AIRLINE_RE.match(call)) and shape in ("bizjet", "turboprop"))
    if airline_call and shape in ("bizjet", "turboprop", "prop2"):
        return "ifr"
    if shape in ("prop1", "prop2") and call and (call == str(registration or "").replace("-", "").upper() or REGISTRATION_RE.match(call)):
        return "vfr"
    return "unknown"
